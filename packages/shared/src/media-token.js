import { createHmac, timingSafeEqual } from 'node:crypto';

/**
 * Signed, expiring tokens that grant read access to exactly ONE stored media file through the media gateway.
 *
 * token = base64url(JSON {k: storage key, t: mime type, e: expiry unix seconds}) + "." + base64url(HMAC-SHA256)
 *
 * The gateway verifies the token with the signing key alone: it needs no database and no access to any other
 * secret, which is what makes it safe to expose through a tunnel.
 * Kept in its own module (not re-exported from the package index) because it uses node:crypto.
 */

const b64 = (buf) => Buffer.from(buf).toString('base64url');
const mac = (key, data) => createHmac('sha256', key).update(data).digest();

/** Same shape as the storage keys generated by the API: YYYY/MM/<uuid>.<ext> */
export const STORAGE_KEY_RE = /^\d{4}\/\d{2}\/[0-9a-f-]{36}\.[a-z0-9]{2,5}$/;

export function signMediaToken({ key, storageKey, mimeType, expiresAtSeconds }) {
  const payload = b64(JSON.stringify({ k: storageKey, t: mimeType, e: expiresAtSeconds }));
  return `${payload}.${b64(mac(key, payload))}`;
}

/** @returns {{storageKey: string, mimeType: string, expiresAtSeconds: number}|null} null for anything invalid or expired */
export function verifyMediaToken({ key, token, nowSeconds = Math.floor(Date.now() / 1000) }) {
  if (typeof token !== 'string' || token.length > 700) return null;
  const [payload, sig, extra] = token.split('.');
  if (!payload || !sig || extra !== undefined) return null;
  let given;
  try {
    given = Buffer.from(sig, 'base64url');
  } catch {
    return null;
  }
  const expected = mac(key, payload);
  if (given.length !== expected.length || !timingSafeEqual(given, expected)) return null;
  let data;
  try {
    data = JSON.parse(Buffer.from(payload, 'base64url').toString('utf8'));
  } catch {
    return null;
  }
  if (typeof data?.k !== 'string' || typeof data?.t !== 'string' || !Number.isFinite(data?.e)) return null;
  if (data.e < nowSeconds || !STORAGE_KEY_RE.test(data.k)) return null;
  return { storageKey: data.k, mimeType: data.t, expiresAtSeconds: data.e };
}
